module dadda_8bits(n1, n2, out);
    input [7:0] n1, n2;
    output [15:0] out;
    wire [63:0] c0;
    wire [11:0] c1;
    wire [27:0] c2;
    wire [19:0] c3;
    wire [23:0] c4;
    wire [15:0] c5;
    genvar i, j;

    generate
        for(i = 0; i < 8; i = i+1)
        begin: ands_n1
            for(j = 0; j < 8; j = j+1)
            begin: ands_n2
                assign c0[(j*8)+i] = n1[i] & n2[j]; 
            end
        end
    endgenerate

    //primeira camada de somadores
    ha p1_1(c0[6], c0[13], c1[0], c1[1]);
    fa p1_2(c0[7], c0[14], c0[21], c1[2], c1[3]);
    ha p1_4(c0[28], c0[35], c1[4], c1[5]);
    fa p1_5(c0[15], c0[22], c0[29], c1[6], c1[7]);
    ha p1_7(c0[36], c0[43], c1[8], c1[9]);
    fa p1_8(c0[23], c0[30], c0[37], c1[10], c1[11]);

    //segunda camada de somadores
    ha p2_1(c0[4], c0[11], c2[0], c2[1]);
    fa p2_2(c0[5], c0[12], c0[19], c2[2], c2[3]);
    ha p2_3(c0[26], c0[33], c2[4], c2[5]);
    fa p2_4(c0[20], c0[27], c0[34], c2[6], c2[7]);
    fa p2_5(c0[43], c0[50], c1[0], c2[8], c2[9]);
    fa p2_6(c0[42], c0[49], c0[56], c2[10], c2[11]);
    fa p2_7(c1[1], c1[2], c1[4], c2[12], c2[13]);
    fa p2_8(c0[50], c0[57], c1[3],c2[14], c2[15]);
    fa p2_9(c1[5], c1[6], c1[8], c2[16], c2[17]);
    fa p2_10(c0[44], c0[51], c0[58], c2[18], c2[19]);
    fa p2_11(c1[7], c1[9], c1[10], c2[20], c2[21]);
    fa p2_12(c0[31], c0[38], c0[45], c2[22], c2[23]);
    fa p2_13(c0[52], c0[59], c1[11], c2[24], c2[25]);
    fa p2_14(c0[39], c0[46], c0[54], c2[26], c2[27]);

    //terceira camada de somadores
    ha p3_1(c0[3], c0[10], c3[0], c3[1]);
    fa p3_2(c0[18], c0[25], c0[32], c3[2], c3[3]);
    fa p3_3(c0[40], c2[1], c2[2], c3[4], c3[5]);
    fa p3_4(c2[3], c2[5], c2[6], c3[6], c3[7]);
    fa p3_5(c2[7], c2[9], c2[10], c3[8], c3[9]);
    fa p3_6(c2[11], c2[13], c2[14], c3[10], c3[11]);
    fa p3_7(c2[15], c2[17], c2[18], c3[12], c3[13]);
    fa p3_8(c2[19], c2[21], c2[22], c3[14], c3[15]);
    fa p3_9(c0[60], c2[23], c2[25], c3[16], c3[17]);
    fa p3_10(c0[47], c0[54], c0[61], c3[18], c3[19]);

    //quarta camada de somadores
    ha p4_1(c0[2], c0[9], c4[0], c4[1]);
    fa p4_2(c0[17], c0[24], c3[0], c4[2], c4[3]);
    fa p4_3(c2[0], c3[1], c3[2], c4[4], c4[5]);
    fa p4_4(c2[4], c3[3], c3[4], c4[6], c4[7]);
    fa p4_5(c2[8], c3[5], c3[6], c4[8], c4[9]);
    fa p4_6(c2[12], c3[7], c3[8], c4[10], c4[11]);
    fa p4_7(c2[16], c3[9], c3[10], c4[12], c4[13]);
    fa p4_8(c2[20], c3[11], c3[12], c4[14], c4[15]);
    fa p4_9(c2[24], c3[13], c3[14], c4[16], c4[17]);
    fa p4_10(c2[26], c3[15], c3[16], c4[18], c4[19]);
    fa p4_11(c2[27], c3[17], c3[18], c4[20], c4[21]);
    fa p4_12(c3[19], c0[55], c0[63], c4[22], c4[23]);

    //camada final de somadores
    assign out[0] = c0[0];
    ha p5_1(c0[1], c0[8], out[1], c5[0]);
    fa p5_2(c0[5], c4[0], c5[0], out[2], c5[1]);
    fa p5_3(c3[0], c4[1], c5[1], out[3], c5[2]);
    fa p5_4(c4[2], c4[3], c5[2], out[4], c5[3]);
    fa p5_5(c4[4], c4[5], c5[3], out[5], c5[4]);
    fa p5_6(c4[6], c4[7], c5[4], out[6], c5[5]);
    fa p5_7(c4[8], c4[9], c5[5], out[7], c5[6]);
    fa p5_8(c4[10], c4[11], c5[6], out[8], c5[7]);
    fa p5_9(c4[12], c4[13], c5[7], out[9], c5[8]);
    fa p5_10(c4[14], c4[15], c5[8], out[10], c5[9]);
    fa p5_11(c4[16], c4[17], c5[9], out[11], c5[10]);
    fa p5_12(c4[18], c4[19], c5[10], out[12], c5[11]);
    fa p5_13(c4[20], c4[21], c5[11], out[13], c5[12]);
    fa p5_14(c4[22], c4[23], c5[12], out[14], out[15]);
endmodule